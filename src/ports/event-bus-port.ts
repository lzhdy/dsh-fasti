/**
 * 事件总线端口 —— 内核只认这个接口（平台化宿主中立 H1 切片 3）。
 *
 * 把"按名订阅宿主事件"从具体事件系统（cordis Events、自研 EventEmitter、headless
 * 内存队列等）里抽象出来：内核只说"我要听这个名字的事件，发生时调用我"，不认识
 * 任何宿主的事件服务。
 *
 * 硬语义（来自 dsh 实测的丢首事件红线，适配器与调用方都必须遵守）：
 *  - **同步注册**：`on` 必须在调用它的那个同步执行栈内立即完成登记，不得推迟到
 *    微任务、Promise 回调或定时器之后。否则订阅生效前派发的首个事件会直接丢失。
 *  - **随作用域自动退订**：监听器归属当前运行作用域，作用域卸载时由适配器保证移除，
 *    因此本端口不返回手动取消句柄（当前也没有需要提前退订的消费者，YAGNI）。
 *  - 回调载荷统一为不定参数数组；具体事件有几个参数、各是什么形状，由订阅方凭它
 *    订阅的事件名自行约定，端口不内置任何具体事件名或载荷类型。
 */
export interface EventBusPort {
  /**
   * 同步订阅一个具名事件。
   *
   * @param eventName 事件名（如 dsh 的 'session/event'）；端口只透传，不解释。
   * @param listener 事件派发时被同步调用的监听器，载荷原样作为不定参数传入。
   */
  on(eventName: string, listener: (...args: unknown[]) => void): void;
}
