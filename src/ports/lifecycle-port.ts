/**
 * 生命周期端口 —— 内核只认这个接口（平台化宿主中立 H1 切片 2）。
 *
 * 内核/装配层占有的资源（后台循环、句柄、事件订阅）需要在宿主作用域卸载时被释放，
 * 但"作用域何时卸载、如何调度清理"是宿主的事。本端口只声明一件事：把清理函数
 * 登记进来，作用域结束时由宿主保证调用它。内核因此不用认识 cordis 的 ctx.effect。
 *
 * 中立性：onDispose 表达的是通用资源清理，不是任何平台的名词。label 仅为可选诊断名，
 * 不影响行为；不需要诊断的后端可以忽略它。
 */
export interface LifecyclePort {
  /**
   * 登记一个随当前作用域卸载而运行的清理函数。
   *
   * 约定：登记立即生效；清理函数应当同步、幂等、不向外抛错（具体资源各自保证）。
   * 多个清理之间的回收顺序由适配器/宿主定义，调用方不应依赖跨资源顺序。
   *
   * @param cleanup 卸载时执行的释放逻辑。
   * @param label 可选诊断名，仅用于宿主侧排障展示。
   */
  onDispose(cleanup: () => void, label?: string): void;
}
